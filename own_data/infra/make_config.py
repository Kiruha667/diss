"""Build own_data/config/glm-4.6_v1.0.yaml — the mini-swe-agent run config of PROTOCOL.md 1.0 — from the corpus
config own_data/leaderboard_configs/20251201_mini-v1.17.1_glm-4.6.json, verbatim except:
  - model.model_kwargs.api_key is removed (the key comes from the process environment, never from a file);
  - environment.image is left out (mini-extra swebench sets it per task, as it did for the corpus);
  - environment.environment_class: docker and model.model_class: litellm are the runner's selectors (popped by
    mini-swe-agent before the config objects are built, so they never appear in info.config).
Then checks that the result reproduces the corpus config field by field. Run from the repository root with any
Python that has pyyaml.
"""
import hashlib
import json
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "own_data/leaderboard_configs/20251201_mini-v1.17.1_glm-4.6.json"
OUT = ROOT / "own_data/config/glm-4.6_v1.0.yaml"


class _Block(yaml.SafeDumper):
    pass


def _str(dumper, s):
    return dumper.represent_scalar("tag:yaml.org,2002:str", s, style="|" if "\n" in s else None)


_Block.add_representer(str, _str)

corpus = json.loads(SRC.read_text(encoding="utf-8"))["config"]
agent = dict(corpus["agent"])
model = dict(corpus["model"])
model["model_kwargs"] = {k: v for k, v in model["model_kwargs"].items() if k != "api_key"}
model["model_class"] = "litellm"
env = {k: v for k, v in corpus["environment"].items() if k != "image"}
env["environment_class"] = "docker"
cfg = {"agent": agent, "environment": env, "model": model}
OUT.parent.mkdir(parents=True, exist_ok=True)
header = ("# mini-swe-agent 1.17.1 run config, PROTOCOL.md 1.0 (own corpus). Generated by own_data/infra/make_config.py\n"
          "# from the corpus run 20251201_mini-v1.17.1_glm-4.6; the API key is NOT part of this file.\n")
OUT.write_text(header + yaml.dump(cfg, Dumper=_Block, sort_keys=False, allow_unicode=True, width=10_000),
               encoding="utf-8", newline="\n")

# round trip: every corpus field except the removed / runner-set ones must come back unchanged
back = yaml.safe_load(OUT.read_text(encoding="utf-8"))
assert back["agent"] == corpus["agent"]
assert {k: v for k, v in back["environment"].items() if k != "environment_class"} == \
    {k: v for k, v in corpus["environment"].items() if k != "image"}
bm = {k: v for k, v in back["model"].items() if k != "model_class"}
cm = dict(corpus["model"])
cm["model_kwargs"] = {k: v for k, v in cm["model_kwargs"].items() if k != "api_key"}
assert bm == cm, (bm, cm)
print("config identical to the corpus config except api_key / image; sha256",
      hashlib.sha256(OUT.read_bytes()).hexdigest())

# PROTOCOL 1.1 (own_data/THINKING_CHECK.md): 1.0 + z.ai's thinking switched off, sent by litellm as extra_body
OUT11 = ROOT / "own_data/config/glm-4.6_v1.1.yaml"
cfg11 = yaml.safe_load(OUT.read_text(encoding="utf-8"))
cfg11["model"]["model_kwargs"]["extra_body"] = {"thinking": {"type": "disabled"}}
header11 = ("# mini-swe-agent 1.17.1 run config, PROTOCOL.md 1.1 (own corpus). Generated by own_data/infra/make_config.py:\n"
            "# glm-4.6_v1.0.yaml + model.model_kwargs.extra_body.thinking.type = disabled (see own_data/THINKING_CHECK.md).\n"
            "# The API key is NOT part of this file.\n")
OUT11.write_text(header11 + yaml.dump(cfg11, Dumper=_Block, sort_keys=False, allow_unicode=True, width=10_000),
                 encoding="utf-8", newline="\n")
back11 = yaml.safe_load(OUT11.read_text(encoding="utf-8"))
diff = {k: v for k, v in back11["model"]["model_kwargs"].items() if back["model"]["model_kwargs"].get(k) != v}
assert diff == {"extra_body": {"thinking": {"type": "disabled"}}} and \
    {k: v for k, v in back11.items() if k != "model"} == {k: v for k, v in back.items() if k != "model"}
print("v1.1 = v1.0 + extra_body.thinking.type=disabled; sha256", hashlib.sha256(OUT11.read_bytes()).hexdigest())
